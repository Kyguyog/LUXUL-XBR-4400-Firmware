            <h2>Ping</h2>

            <p>Ping is a software utility to test the reachability of a host on a network and to measure the round-trip time for messages sent from the router to a destination device and back.<br /><br />
                To use Ping, simply enter a valid IP address in the text field and click the Start button. Ping will display the Ping command with the IP address you entered and will attempt to transmit five packets. If the device is reachable and responds, Ping will print a line for each packet along with the time it took and some overall statistics.<br /><br />
                Note: Not all devices will respond to Ping even though they may be reachable.</p>

