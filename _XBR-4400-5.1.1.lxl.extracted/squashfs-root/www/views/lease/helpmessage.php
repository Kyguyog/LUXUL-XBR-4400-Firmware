            <h2>Static Leases</h2>
            <p>Use this screen to reserve an IP address for a specific device. Anytime the device is on the network it will be automatically assigned the specified IP address.<br /><br />
                There are two methods of creating Static Leases. In the Discovered Clients page you can put a check mark by each device you want to create a Static Lease for, then click the Add button.
                Select All adds check marks to every item. Unselect All removes all check marks.<br /><br />
                The Add Lease Table allows you to create a Static Lease for the device not shown in the Discovered Clients table.
                Enter a Description for the device - this is a common name you use for the device (i.e. Camera1).
                Do not use spaces or specialcharacters in host name. A - (dash) or _ (underscore) is allowed. Next enter the IP address you want to assign to this device.
                This IP address can be in the DHCP pool or outside the DHCP pool. Enter the MAC address of the device.
                Press the ADD button to create the Static Lease. The Cancel button clears the row without saving the change.<br /><br />
                The Assigned Leases shows all Static Leases that have been created. Here you can modify or delete Static Leases. Highlight the row you want to modify or delete and press the appropriate button.
                If you are modifying the row, click on the Save button to save your changes.
                Cancel reverts the row to the previous state. The Delete button removes the row.<br /><br />
                The Apply button updates the saved information. The Refresh button updates the tables. The Reboot button is provided for user convenience.<br /><br />
                If the device for which you're creating the static lease is already on the network you may have to disconnect and reconnect it for the new lease to become active.<br /><br />
                NOTE: The hostname may be provided by the client and is shown for informational purposes only.
            </p>
