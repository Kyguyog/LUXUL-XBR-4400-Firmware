            <h2>VLAN</h2>

            <p>A VLAN is a group of devices that are associated by function or other shared characteristics.
                Unlike LANs, which are usually geographically based, VLANs can group devices without regard to the
                physical location of the equipment or users. You can create up to eight new VLANS.
                <br/><br/>
                NOTE: Improperly setting up VLANs can prevent you from accessing the network. A factory default may be
                required to clear the improperly setup VLAN.
                <br/><br/>
                Configuration Steps:
