$(document).ready(function () {
    displayLeftNav();

    $('#restore').attr('disabled', true);

    $('#restoreFile').bind('change', function () {
        $("#restoreStatus").slideUp("slow");
        var filename = $('#restoreFile').val();
        if (filename && filename.split('.').pop() == "lxc") {
            $('#restore').removeAttr('disabled');
            $('#invalid_file').slideUp();
        } else {
            $('#restore').attr('disabled', true);
            $('#invalid_file').slideDown();
        }
    });

    $('#restoreForm').bind('submit', function () {
        $('#restoreFile').readonly = true;
        $('#restore').disabled = true;
        $('#upgrading').slideDown();
    });

    if ($("#restoreError").text().indexOf("different FW version.") > 0) {
        if (confirm("The configuration file you're restoring was generated by different firmware. " +
                "Restoring this config file may result in failed or erratic operation. Do you want to proceed?") == true) {

            window.location = "/backup/forceRestoreFile";

        } else {
            return false;
        }
    }

    $("#btnBackup").click(function () {
        window.location = "/backup/download";
    });

    var is_mac = navigator.userAgent.toLowerCase().indexOf('mac') > -1;
    var is_firefox = navigator.userAgent.toLowerCase().indexOf('firefox') > -1;
    var is_chrome = navigator.userAgent.toLowerCase().indexOf('chrome') > -1;

    if (is_mac) {
        if(is_firefox) {
            document.getElementById("fileLabel").setAttribute("id", "fileLabel1");
        } else if (is_chrome) {
            document.getElementById("fileLabel").setAttribute("id", "fileLabel2");
        }

    } else {
        if (is_chrome) {
            document.getElementById("fileLabel").setAttribute("id", "fileLabel3");
            $("#restore").css("margin-top", "4px");
        } else if (is_firefox) {
            document.getElementById("fileLabel").setAttribute("id", "fileLabel4");
            $("#restore").css("margin-top", "6px");

        }
    }

});