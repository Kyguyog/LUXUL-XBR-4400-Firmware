            <h2>Dynamic DNS</h2>

            <p>Use the DDNS or Dynamic DNS (Domain Name Service) to automatically update the Domain Name System.
               <br/><br/>
               If you set up a VPN on the router and it is assigned a DHCP IP address and the IP address changes, you
               won't be able to connect.
               DDNS allows the VPN service to find the router even if the IP address changes.
            </p>

