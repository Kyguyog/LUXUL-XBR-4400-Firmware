            <h2>Trace Route</h2>

            <p>Traceroute is a utility for displaying the route (path) and measuring transit delays of packets across a network. The route is recorded as the round-trip times of the packets received from each successive host in the route.<br /><br />
                To use traceroute, simply enter a valid IP address in the text field and click the Start button. The route will be displayed.</p>

