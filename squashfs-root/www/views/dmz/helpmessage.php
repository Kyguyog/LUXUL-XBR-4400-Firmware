            <h2>DMZ</h2>

            <p>The purpose of a DMZ is to add an additional layer of security to the local area network.
               An external attacker only has direct access to equipment in the DMZ, rather than any other part of the
               network.
               If you want to open up all outside access to a device, place this device in the DMZ.
               You do this by enabling the DMZ and entering the IP address of the device.
               For security reasons the DMZ IP address needs to be static lease or static IP address.</p>

