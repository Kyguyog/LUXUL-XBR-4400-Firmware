            <h2>Multi-WAN</h2>

            <p>Multi-WAN enables your router to be connected to more than one Internet Provider simultaneously.
                It can balance network traffic between two or more provider networks and provide fail over support
                if one of the connections goes down.
                <br/><br/>
                Multi-WAN is an advanced user function and may have implications on other Router features and functions.
                To disable Multi-WAN you must restore the Router to factory defaults.
            </p>

